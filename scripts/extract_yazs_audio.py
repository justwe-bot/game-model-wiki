def align4(value: int) -> int:
    return (value + 3) & ~3


def load_clip_sources(data_dir: Path) -> dict[str, tuple[str, object]]:
    """Return clip name -> (source file, AudioClip object); first source wins."""
    bundles = data_dir / "StreamingAssets" / "AssetBundles"
    candidates: list[Path] = []
    for name in SOURCE_ORDER:
        path = bundles / name if name.startswith("game") or name == "prototypescene" else data_dir / name
        if path.is_file():
            candidates.append(path)
    # Anything not covered by SOURCE_ORDER still gets scanned, deterministically.
    known = {p.name for p in candidates}
    for path in sorted(data_dir.iterdir()) + sorted(bundles.iterdir()):
        if path.is_file() and path.name not in known and path.stat().st_size > 1024:
            candidates.append(path)
            known.add(path.name)

    found: dict[str, tuple[str, object]] = {}
    for path in candidates:
        try:
            env = UnityPy.load(str(path))
        except Exception as exc:  # noqa: BLE001 - report and continue
            print(f"  ! 跳过 {path.name}: {type(exc).__name__}: {exc}", file=sys.stderr)
            continue
        added = 0
        for obj in env.objects:
            if obj.type.name != "AudioClip":
                continue
            try:
                name = obj.peek_name()
            except Exception:  # noqa: BLE001
                continue
            if not name or name in found:
                continue
            try:
                found[name] = (path.name, obj.read())
            except Exception as exc:  # noqa: BLE001
                print(f"  ! 读取失败 {name}: {type(exc).__name__}: {exc}", file=sys.stderr)
                continue
            added += 1
        print(f"  {path.name:30s} +{added:4d}  (累计 {len(found)})")
    return found


def slugify(name: str) -> str:
    text = name.lower()
    text = re.sub(r"[^a-z0-9]+", "-", text)
    return text.strip("-") or "clip"


def write_m4a(ffmpeg: str, wav_bytes: bytes, wav_path: Path, m4a_path: Path, bitrate: str) -> None:
    wav_path.parent.mkdir(parents=True, exist_ok=True)
    m4a_path.parent.mkdir(parents=True, exist_ok=True)
    wav_path.write_bytes(wav_bytes)
    command = [
        ffmpeg, "-y", "-loglevel", "error",
        "-i", str(wav_path),
        "-c:a", "aac", "-b:a", bitrate,
        str(m4a_path),
    ]
    completed = subprocess.run(command, capture_output=True, text=True)
    if completed.returncode != 0:
        raise RuntimeError(f"ffmpeg failed for {wav_path.name}: {completed.stderr.strip()}")
    wav_path.unlink(missing_ok=True)


def match_group(name: str, rules: list[tuple[re.Pattern, dict]]) -> dict | None:
    for pattern, meta in rules:
        if pattern.match(name):
            return meta
    return None


def build_rules() -> list[tuple[re.Pattern, dict]]:
    return [(re.compile(pattern), meta) for pattern, meta in GROUP_META]


def parse_wav_info(data: bytes) -> tuple[float, int, int]:
    """Return (durationSec, sampleRate, channels) from a RIFF/WAVE payload."""
    import struct

    channels = struct.unpack_from("<H", data, 22)[0]
    sample_rate = struct.unpack_from("<I", data, 24)[0]
    bits = struct.unpack_from("<H", data, 34)[0]
    data_size = 0
    offset = 12
    while offset + 8 <= len(data):
        chunk_id = data[offset:offset + 4]
        chunk_size = struct.unpack_from("<I", data, offset + 4)[0]
        if chunk_id == b"data":
            data_size = chunk_size
            break
        offset += 8 + chunk_size + (chunk_size % 2)
    seconds = data_size / (sample_rate * channels * max(bits // 8, 1)) if sample_rate else 0.0
    return seconds, sample_rate, channels


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--game", type=Path, default=DEFAULT_GAME,
                        help="path to '<Game>_Data' directory")
    parser.add_argument("--bitrate", default="96k", help="AAC bitrate for preview files")
    parser.add_argument("--limit", type=int, default=0, help="only process the first N clips")
    args = parser.parse_args()

    if not args.game.is_dir():
        print(f"游戏数据目录不存在: {args.game}", file=sys.stderr)
        return 2

    try:
        import imageio_ffmpeg
    except ImportError:
        print("需要 imageio-ffmpeg 提供 ffmpeg 可执行文件", file=sys.stderr)
        return 2
    ffmpeg = imageio_ffmpeg.get_ffmpeg_exe()

    print("扫描音频资源…")
    clips = load_clip_sources(args.game)
    print(f"共 {len(clips)} 个唯一音频片段\n")

    rules = build_rules()
    unmatched = sorted(name for name in clips if match_group(name, rules) is None)
    if unmatched:
        print(f"有 {len(unmatched)} 个音频没有匹配到任何分组，请补充 GROUP_META：", file=sys.stderr)
        for name in unmatched:
            print(f"  - {name}", file=sys.stderr)
        return 3

    names = sorted(clips)
    if args.limit:
        names = names[: args.limit]

    tmp_dir = ROOT / "work" / "yazs-wav"
    SOUNDS_DIR.mkdir(parents=True, exist_ok=True)

    entries: dict[str, dict] = {}
    order: list[str] = []
    for index, name in enumerate(names, 1):
        source, clip = clips[name]
        _filename, payload = next(iter(clip.samples.items()))
        short = slugify(name)
        if len(short) > 60:
            short = short[:60].rstrip("-")
        m4a_path = SOUNDS_DIR / f"{short}.m4a"
        wav_path = tmp_dir / f"{short}.wav"
        write_m4a(ffmpeg, payload, wav_path, m4a_path, args.bitrate)
        seconds, rate, channels = parse_wav_info(payload)

        meta = match_group(name, rules)
        slug = meta["slug"]
        if slug not in entries:
            entries[slug] = {
                "slug": slug,
                "name": meta["name"],
                "nameEn": meta["nameEn"],
                "tier": meta["tier"],
                "status": "已提取",
                "sourceName": name if not re.search(r"\d", name) else re.sub(r"\d+", "*", name),
                "summary": meta["summary"],
                "usedBy": list(meta.get("usedBy", [])),
                "loop": bool(meta.get("loop", False)),
                "durationSec": 0.0,
                "clipCount": 0,
                "clips": [],
            }
            order.append(slug)
        entry = entries[slug]
        entry["clips"].append({
            "name": name,
            "source": source,
            "file": f"sounds/{GAME_SLUG}/{m4a_path.name}",
            "durationSec": round(seconds, 3),
            "sampleRate": rate,
            "channels": channels,
            "previewSizeKB": round(m4a_path.stat().st_size / 1024, 1),
        })
        entry["clipCount"] += 1
        entry["durationSec"] = round(entry["durationSec"] + seconds, 3)
        if index % 50 == 0 or index == len(names):
            print(f"  已导出 {index}/{len(names)} …")

    catalog = []
    for tier in TIER_ORDER:
        for slug in order:
            if entries[slug]["tier"] == tier:
                catalog.append(entries[slug])
    for slug in order:  # any tier typo would otherwise silently drop entries
        if entries[slug] not in catalog:
            catalog.append(entries[slug])

    CATALOG_PATH.parent.mkdir(parents=True, exist_ok=True)
    CATALOG_PATH.write_text(json.dumps(catalog, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"\n写出 {CATALOG_PATH.relative_to(ROOT)}：{len(catalog)} 个音频条目 / "
          f"{sum(e['clipCount'] for e in catalog)} 个片段")

    update_games_json(catalog)
    return check_weapon_links(catalog)


def check_weapon_links(catalog: list[dict]) -> int:
    """Fail if weapons.json points at a sound entry this run did not produce."""
    if not WEAPONS_PATH.exists():
        return 0
    known = {entry["slug"] for entry in catalog}
    weapons = json.loads(WEAPONS_PATH.read_text(encoding="utf-8")).get("weapons", [])
    broken = [
        (weapon["key"], slug)
        for weapon in weapons
        for slug in weapon.get("audio", [])
        if slug not in known
    ]
    unlinked = [weapon["name"] for weapon in weapons if not weapon.get("audio")]
    if broken or unlinked:
        print(f"weapons.json 交叉校验失败：无效引用 {broken}；无音效武器 {unlinked}", file=sys.stderr)
        return 5
    print(f"weapons.json 交叉校验通过：{len(weapons)} 把武器全部关联到已导出的音效条目")
    return 0


